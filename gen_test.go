func TestGenerateModels(t *testing.T) {
	src, pkg, err := Generate(Options{Dir: "testdata/models"})
	if err != nil {
		t.Fatal(err)
	}
	s := string(src)
	if pkg != "models" || !strings.HasPrefix(s, "// Code generated by orm-gen. DO NOT EDIT.") {
		t.Fatalf("header/package %q:\n%s", pkg, s)
	}
	for _, want := range []string{
		`var userOrmColumns = []string{"id", "name", "name", "email", "status", "born", "created_by", "created_at", "updated_at", "deleted_at"}`,
		`return []any{&m.BaseModel.ID, &m.Name, &m.Nick, &m.Email, &m.Status, &m.Born, &m.Audit.CreatedBy, &m.Timestamps.CreatedAt, &m.Timestamps.UpdatedAt, &m.SoftDeletes.DeletedAt}`,
		`"name":       m.Name,`,
		`if err := orm.Assign(&m.Audit.CreatedBy, v); err != nil {`,
		`return fmt.Errorf("orm: field %q (db:%q): %w", "Nick", "name", err)`,
		`var postOrmColumns = []string{"id", "user_id", "title"}`,
	} {
		if !strings.Contains(s, want) {
			t.Errorf("missing %s", want)
		}
	}
	for _, not := range []string{"(*Audit)", "m.Nick,\n", "Skip", "Plain", "Posts", "hidden", "note", "NoColumns", "Box", "testOnly"} {
		if strings.Contains(s, not) {
			t.Errorf("unexpected %q", not)
		}
	}

	only, _, err := Generate(Options{Dir: "testdata/models", Types: []string{"Post"}})
	if err != nil || strings.Contains(string(only), "(*User)") || !strings.Contains(string(only), "(*Post)") {
		t.Fatalf("-type Post: %v\n%s", err, only)
	}
	tests, _, err := Generate(Options{Dir: "testdata/models", Tests: true, Types: []string{"testOnly"}})
	if err != nil || !strings.Contains(string(tests), `[]string{"x"}`) {
		t.Fatalf("-tests: %v\n%s", err, tests)
	}
}

func writePkg(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func TestGenerateErrors(t *testing.T) {
	cases := map[string]struct {
		files map[string]string
		opts  Options
		want  string
	}{
		"no tags":     {map[string]string{"a.go": "package a\ntype A struct{ X int }\nfunc (A) TableName() string { return \"a\" }\n"}, Options{}, "no model"},
		"no models":   {map[string]string{"a.go": "package a\ntype A struct{ X int `db:\"x\"` }\n"}, Options{}, "no model"},
		"no such":     {map[string]string{"a.go": "package a\ntype A struct{ X int `db:\"x\"` }\n"}, Options{Types: []string{"B"}}, "no struct type B"},
		"empty":       {map[string]string{"a.go": "package a\ntype A struct{ X int }\n"}, Options{Types: []string{"A"}}, "no fields with db tags"},
		"generic":     {map[string]string{"a.go": "package a\ntype A[T any] struct{ X T `db:\"x\"` }\n"}, Options{Types: []string{"A"}}, "generic"},
		"foreign":     {map[string]string{"a.go": "package a\nimport \"other\"\ntype A struct{ other.Base\n X int `db:\"x\"` }\n"}, Options{Types: []string{"A"}}, "cannot see"},
		"unknown orm": {map[string]string{"a.go": "package a\nimport \"orm\"\ntype A struct{ orm.Unknown\n X int `db:\"x\"` }\n"}, Options{Types: []string{"A"}}, "cannot see"},
		"self":        {map[string]string{"a.go": "package a\ntype A struct{ B\n X int `db:\"x\"` }\ntype B struct{ A }\n"}, Options{Types: []string{"A"}}, "embeds itself"},
		"package orm": {map[string]string{"a.go": "package orm\ntype A struct{ X int `db:\"x\"` }\n"}, Options{Types: []string{"A"}}, "package orm"},
		"syntax":      {map[string]string{"a.go": "package a\ntype A struct{\n"}, Options{}, "expected"},
		"no files":    {map[string]string{"README": "x"}, Options{}, "no Go files"},
		"two pkgs":    {map[string]string{"a.go": "package a\n", "b.go": "package b\n"}, Options{Types: []string{"X"}}, "several packages"},
	}
	for name, c := range cases {
		t.Run(name, func(t *testing.T) {
			c.opts.Dir = writePkg(t, c.files)
			_, _, err := Generate(c.opts)
			if err == nil || !strings.Contains(err.Error(), c.want) {
				t.Fatalf("want %q, got %v", c.want, err)
			}
		})
	}
	if _, _, err := Generate(Options{Dir: filepath.Join(t.TempDir(), "missing")}); err == nil {
		t.Fatal("missing directory")
	}
}

func TestGenerateEdgeCases(t *testing.T) {
	dir := writePkg(t, map[string]string{
		"a.go": "package a\n\nimport o \"orm\"\n\ntype ID int64\n\n" +
			"type Base struct{ Note string `db:\"note\"` }\n\n" +
			"type A struct {\n\tID `db:\"id\"`\n\t*Base `db:\"base\"`\n\to.BaseModel `db:\"-\"`\n\tName string `db:\"name\"`\n}\n",
		"ignored.go": "//go:build ignore\n\npackage main\n\ntype Z struct{ Q int `db:\"q\"` }\n",
		"orm_gen.go": "package a\n\ntype Old struct{ Q int `db:\"q\"` }\n", // previous output is not read
		"a_test.go":  "package a_test\n\ntype T struct{ X int `db:\"x\"` }\n",
		"m.go":       "package a\n\ntype M struct{ X int `db:\"x\"` }\n\nfunc (M) TableName() string { return \"m\" }\n",
	})
	src, _, err := Generate(Options{Dir: dir, Types: []string{"A"}})
	if err != nil {
		t.Fatal(err)
	}
	// orm.BaseModel is walked whatever its tag (the orm walks embedded structs).
	if !strings.Contains(string(src), `[]string{"id", "base", "id", "name"}`) || strings.Contains(string(src), "Old") {
		t.Fatalf("%s", src)
	}
	// With -tests the external test package is picked by the type name.
	src, pkg, err := Generate(Options{Dir: dir, Tests: true, Types: []string{"T"}})
	if err != nil || pkg != "a_test" {
		t.Fatalf("%v %s\n%s", err, pkg, src)
	}
	// Without -type, the non-test package.
	if _, pkg, err := Generate(Options{Dir: dir, Tests: true}); err != nil || pkg != "a" {
		t.Fatalf("%v %s", err, pkg)
	}
}

func TestRun(t *testing.T) {
	dir := writePkg(t, map[string]string{"a.go": "package a\n\ntype A struct{ X int `db:\"x\"` }\n\nfunc (*A) TableName() string { return \"a\" }\n"})
	var out, errb bytes.Buffer
	if code := run([]string{"-check", dir}, &out, &errb); code != 1 || !strings.Contains(errb.String(), "out of date") {
		t.Fatalf("check before generate: %d %s", code, errb.String())
	}
	if code := run([]string{"-type", " A, ", dir}, &out, &errb); code != 0 {
		t.Fatalf("%d %s", code, errb.String())
	}
	if _, err := os.Stat(filepath.Join(dir, "orm_gen.go")); err != nil {
		t.Fatal(err)
	}
	// CRLF checkouts (Windows) are up to date too.
	data, _ := os.ReadFile(filepath.Join(dir, "orm_gen.go"))
	os.WriteFile(filepath.Join(dir, "orm_gen.go"), bytes.ReplaceAll(data, []byte("\n"), []byte("\r\n")), 0o644)
	out.Reset()
	if code := run([]string{"-check", dir}, &out, &errb); code != 0 || !strings.Contains(out.String(), "up to date") {
		t.Fatalf("check after generate: %d %s", code, errb.String())
	}
	if code := run([]string{"-tests", "-o", "x_test.go", dir}, &out, &errb); code != 0 {
		t.Fatal(errb.String())
	}
	if _, err := os.Stat(filepath.Join(dir, "x_test.go")); err != nil {
		t.Fatal(err)
	}
	if code := run([]string{dir, dir}, &out, &errb); code != 2 {
		t.Fatal("two directories")
	}
	if code := run([]string{"-nope"}, &out, &errb); code != 2 {
		t.Fatal("unknown flag")
	}
	if code := run([]string{filepath.Join(dir, "missing")}, &out, &errb); code != 1 {
		t.Fatal("missing directory")
	}
	if code := run([]string{"-o", filepath.Join(dir, "no", "dir.go"), dir}, &out, &errb); code != 1 {
		t.Fatal("unwritable output")
	}
	wd, _ := os.Getwd()
	t.Cleanup(func() { os.Chdir(wd) })
	os.Chdir(dir)
	os.Remove("orm_gen.go")
	if code := run(nil, &out, &errb); code != 0 {
		t.Fatal("default directory", errb.String())
	}
}

// TestGeneratedCodeCompiles builds the generated mappers of testdata/models
// against the orm (a devDependency) and checks them at run time.
func TestGeneratedCodeCompiles(t *testing.T) {
	if testing.Short() {
		t.Skip("builds a module")
	}
	goBin, err := exec.LookPath("go")
	if err != nil {
		t.Skip("no go command")
	}
	ormDir, err := exec.Command(goBin, "list", "-m", "-f", "{{.Dir}}", "orm").Output()
	if err != nil || len(bytes.TrimSpace(ormDir)) == 0 {
		t.Skip("orm is not a dependency here (gtr install)")
	}
	dir := t.TempDir()
	models := filepath.Join(dir, "models")
	os.MkdirAll(models, 0o755)
	data, _ := os.ReadFile("testdata/models/models.go")
	os.WriteFile(filepath.Join(models, "models.go"), data, 0o644)
	src, _, err := Generate(Options{Dir: models})
	if err != nil {
		t.Fatal(err)
	}
	os.WriteFile(filepath.Join(models, "orm_gen.go"), src, 0o644)
	os.WriteFile(filepath.Join(models, "models_test.go"), []byte(roundTripTest), 0o644)
	os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module models\n\ngo 1.22\n\nrequire orm v0.0.0\n\nreplace orm => "+strings.TrimSpace(string(ormDir))+"\n"), 0o644)
	cmd := exec.Command(goBin, "test", "-count=1", "./...")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOWORK=off", "GOFLAGS=-mod=mod", "GOPROXY=off")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("%v\n%s", err, out)
	}
}

const roundTripTest = `package models

import (
	"testing"

	"orm"
)

func TestRoundTrip(t *testing.T) {
	var u User
	err := orm.FillStruct(&u, map[string]any{"id": float64(3), "name": "Ann", "status": "active", "created_by": "admin", "born": "2000-01-02T00:00:00Z"})
	if err != nil {
		t.Fatal(err)
	}
	if u.ID != 3 || u.Name != "Ann" || u.Nick != "Ann" || u.Status != "active" || u.CreatedBy != "admin" || u.Born == nil {
		t.Fatalf("%+v", u)
	}
	v := u.OrmValues()
	if v["name"] != "Ann" || v["created_by"] != "admin" || len(v) != 9 {
		t.Fatalf("%v", v)
	}
	if len(u.OrmScanTargets()) != len(u.OrmColumns()) {
		t.Fatal("targets")
	}
	if err := orm.FillStruct(&u, map[string]any{"name": 5}); err != nil { // fmt.Sprint, as reflection does
		t.Fatal(err)
	}
	if err := orm.FillStruct(&u, map[string]any{"id": "x"}); err == nil {
		t.Fatal("string id")
	}
}
`
